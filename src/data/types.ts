// TypeScript view of data/nvl72-topology.schema.json. The schema is the
// contract; tests/schema.test.ts checks the data file against it.

export interface Source {
  url: string;
  section: string;
  /** File name under the guide's _images/ folder. */
  figure?: string;
}

export interface Provenance {
  source: Source;
  assumed?: boolean;
  note?: string;
}

export interface Spec {
  label: string;
  value: string | number;
  unit?: string;
  /** Overrides the component source for this spec. */
  source?: Source;
  assumed?: boolean;
  note?: string;
}

export type Fabric = 'InfiniBand' | 'Ethernet' | null;

export interface Network extends Provenance {
  id: string;
  number: number;
  name: string;
  description: string;
  fabric: Fabric;
  /** Where the fabric is stated, when that is not the network's own source. */
  fabricSource?: Source;
}

export type ComponentType =
  | 'rack'
  | 'compute-tray'
  | 'switch-tray'
  | 'power-shelf'
  | 'tor-switch'
  | 'cpu'
  | 'gpu'
  | 'nic'
  | 'dpu'
  | 'drive'
  | 'switch-asic'
  | 'psu'
  | 'bmc'
  | 'controller'
  | 'port'
  | 'cable-cartridge'
  | 'manifold'
  | 'bus-bar'
  | 'battery'
  | 'memory'
  | 'board'
  | 'connector'
  | 'structure';

/** One section of NVIDIA's documents about a component, generated by scripts/references.mjs. */
export interface Reference {
  document: 'user-guide' | 'service-manual';
  section: string;
  html: string;
  pdf?: string;
  figures?: string[];
}

export interface Component extends Provenance {
  id: string;
  type: ComponentType;
  name: string;
  /** Instances per parent instance; null when the guide does not say. */
  count: number | null;
  parent: string | null;
  description: string;
  function: string;
  networks: string[];
  specs: Spec[];
  /** Extra sources for facts in description and function. */
  textSources?: Source[];
  /** Every section of NVIDIA's documents about this component. */
  references: Reference[];
  rearSide?: boolean;
  /** NVIDIA's first number for these parts (0 for GPU0..GPU3); URL paths stay 1-based. */
  numbering?: { start: number; source: Source };
  /** Networks in `networks` that are this app's reading for this part, not stated for it. */
  assumedNetworks?: string[];
}

export interface RackGroup {
  component: string;
  count: number;
}

export interface Height extends Provenance {
  value: number;
}

export interface RackLayout extends Provenance {
  order: 'top-to-bottom';
  groups: RackGroup[];
  heightsRU?: Record<string, Height>;
  numbering?: Provenance & {
    scheme: 'top-to-bottom-per-type';
    /** Types numbered differently, e.g. power shelves from the bottom up. */
    overrides?: Record<string, Provenance & { order: 'top-to-bottom' | 'bottom-to-top' }>;
  };
}

export type ConnectionKind = 'network' | 'not-connected' | 'nvlink' | 'power' | 'cooling';

export interface Connection extends Provenance {
  id: string;
  from: string;
  to?: string;
  network?: string;
  kind: ConnectionKind;
  description: string;
  /** A conflicting reading kept for the record, shown as a conflict rather than fact. */
  alternative?: boolean;
}

/**
 * A part's place in a schematic tray layout. Top parts: x/z from -0.5 to 0.5
 * across width and depth (+z is the front), w and h as fractions of the tray
 * width, d of its depth. Front parts: y from 0 (bottom) to 1 (top) of the
 * tray, h as a fraction of the tray height.
 */
export interface TraySlot {
  component: string;
  index?: number;
  label?: string;
  face: 'top' | 'front';
  /** Status LEDs drawn on the part's front face. */
  indicators?: { color: 'green' | 'amber'; label: string; unlit?: boolean }[];
  x: number;
  z: number;
  y?: number;
  w: number;
  d: number;
  h: number;
}

export type TrayLinkKind = 'pcie' | 'c2c' | 'clink' | 'nvlink' | 'coolant' | 'power';

/** One end of a link: a part instance, or a named point on the tray. */
export type LinkEnd = { component: string; index?: number; point?: undefined } | { point: string; component?: undefined; index?: undefined };

/** An instance-level connection inside a tray: the "veins" layer. */
export interface TrayLink extends Provenance {
  kind: TrayLinkKind;
  from: LinkEnd;
  to: LinkEnd;
}

export interface TrayPoint {
  id: string;
  label: string;
  x: number;
  z: number;
}

export interface TrayLayout extends Provenance {
  /** Height of the tray in rack units; 1 if omitted. */
  heightRU?: number;
  sources?: Source[];
  notPlaced?: { component: string; reason: string }[];
  slots: TraySlot[];
  points?: TrayPoint[];
  links?: TrayLink[];
}

/** A rear part drawn behind the units, spanning from one unit (or the top) to another (or the bottom). */
export interface RearPart {
  component: string;
  index?: number;
  x: number;
  w: number;
  /** A span from one unit (or "top") to another (or "bottom")... */
  from?: string;
  to?: string;
  /** ...or a short piece at the top, the bottom, or below the stack. */
  at?: 'top' | 'bottom' | 'below';
  heightRU?: number;
  /** Which layer toggle shows it (default parts). */
  layer?: 'parts' | 'structure';
}

/** A connector on the back face of every unit of one type, and the rear part it plugs into. */
export interface UnitConnector {
  unit: string;
  component: string;
  index?: number;
  x: number;
  w: number;
  kind: 'nvlink' | 'cooling' | 'power' | 'ac';
  /** Index into RearLayout.parts; omitted for AC whips, which leave the rack. */
  toPart?: number;
}

export interface RearLayout extends Provenance {
  parts: RearPart[];
  unitConnectors?: UnitConnector[];
}

/** One row of the guide's Table 2.4, mapped to the part it belongs to. */
export interface PcieDevice extends Provenance {
  label: string;
  bus: string;
  interface?: string;
  rdma?: string;
  /** Other spellings NVIDIA's figures print for this label. */
  aliases?: string[];
  component: string;
  index?: number;
}

export interface ProcedureStep {
  text: string;
  source: Source;
  /** A command shown with the step, verbatim from the guide. */
  command?: string;
  /** Selection path to highlight for this step, on an example unit. */
  target?: string;
}

/** A customer-replaceable unit procedure from the service manual. */
export interface Procedure {
  id: string;
  /** service: a customer-replaceable unit (service manual); operation: running the rack (user guide). */
  kind: 'service' | 'operation';
  title: string;
  component: string;
  steps: ProcedureStep[];
}

export interface Software {
  id: string;
  name: string;
  description: string;
  runsOn: string[];
  partOf?: string;
  source: Source;
  note?: string;
}

/** A BMC command from the guide, verbatim. */
export interface Command {
  id: string;
  title: string;
  group: string;
  purpose: string;
  command: string;
  appliesTo: string[];
  source: Source;
  note?: string;
}

export interface SafetyNote {
  id: string;
  title: string;
  text: string;
  components: string[];
  procedures: string[];
  source: Source;
}

/** A term or abbreviation as NVIDIA's documents expand or define it. */
export interface GlossaryTerm {
  id: string;
  term: string;
  aliases?: string[];
  expansion?: string;
  definition: string;
  source: Source;
}

export interface Topology {
  $schema?: string;
  schemaVersion: 1;
  meta: {
    title: string;
    maintainer?: { name: string; email?: string; github?: string; linkedin?: string; repository: string; license: string };
    document: { title: string; date: string; urls: string[]; pdfPages?: Record<string, number>; pdfPagesNote?: string };
    serviceManual?: { title: string; date: string; urls: string[]; pdfPages?: Record<string, number> };
    retrieved: string;
  };
  networks: Network[];
  components: Component[];
  rackLayout: RackLayout;
  trayLayouts?: Record<string, TrayLayout>;
  rearLayout?: RearLayout;
  pcieDevices?: PcieDevice[];
  software?: Software[];
  commands?: Command[];
  commandNotes?: { usage: string; factoryReset: string; source: Source };
  safety?: SafetyNote[];
  glossary?: GlossaryTerm[];
  procedures?: Procedure[];
  /** Which two unit types the NVLink fabric joins, and through which rear part. */
  nvlinkFabric?: Provenance & { endpoints: [string, string]; through: string; description: string; textSources?: Source[] };
  /** Gaps and conflicts in NVIDIA's documents (mirrors docs/OPEN_QUESTIONS.md). */
  openQuestions?: { id: string; title: string; summary: string; components: string[]; kind: 'conflict' | 'gap'; details: string }[];
  connections: Connection[];
}
